#!/usr/bin/env bash
# Verify P0.5 D1: library restructure — cosmos_lab/ package importable, dual-path works.
# Workflow: this is the "verifier" per Phase 1 DEFINE — must return pass/fail, not narrative.

set -uo pipefail

PASS=0
FAIL=0

check() {
    local name="$1"
    shift
    if "$@" >/dev/null 2>&1; then
        echo "  ✅ $name"
        PASS=$((PASS+1))
    else
        echo "  ❌ $name"
        FAIL=$((FAIL+1))
    fi
}

echo "--- Structure ---"
check "cosmos_lab/ directory exists" test -d cosmos_lab
check "cosmos_lab/__init__.py exists" test -f cosmos_lab/__init__.py
check "cosmos_lab/identity/__init__.py exists" test -f cosmos_lab/identity/__init__.py

echo "--- Imports (new path) ---"
check "from cosmos_lab.identity import AgentIdentity" \
    python -c "from cosmos_lab.identity import AgentIdentity"
check "from cosmos_lab.identity import AuditLog" \
    python -c "from cosmos_lab.identity import AuditLog"
check "from cosmos_lab.identity import CapabilityScopedRouter" \
    python -c "from cosmos_lab.identity import CapabilityScopedRouter"
check "from cosmos_lab.identity import CapabilityDenied" \
    python -c "from cosmos_lab.identity import CapabilityDenied"
check "from cosmos_lab import OptimizationConfig" \
    python -c "from cosmos_lab import OptimizationConfig"

echo "--- Backward compat (old path still works) ---"
check "from agent.optimization.identity import AgentIdentity" \
    python -c "from agent.optimization.identity import AgentIdentity"
check "from agent.optimization import OptimizationConfig" \
    python -c "from agent.optimization import OptimizationConfig"

echo "--- Packaging ---"
check "pyproject.toml mentions cosmos-lab" \
    grep -q "cosmos.lab" pyproject.toml
check "pyproject.toml has [project.optional-dependencies]" \
    grep -q "optional-dependencies" pyproject.toml

echo "--- Tests ---"
echo "  Running cosmos-lab tests..."
if uv run pytest tests/optimization/ -q 2>&1 | tail -5; then
    echo "  ✅ tests/optimization/ exits 0"
    PASS=$((PASS+1))
else
    echo "  ❌ tests/optimization/ failed"
    FAIL=$((FAIL+1))
fi

echo "--- Zero-diff invariant ---"
# Owned paths/files (allowed to differ from upstream/main):
#   - cosmos_lab/, agent/optimization/, configs/optimization, tests/optimization (code)
#   - docs/, bin/ (this harness)
#   - pyproject.toml (packaging — we own extras + packages.find for cosmos_lab)
#   - uv.lock (derived from pyproject.toml — auto-regenerated by uv sync)
#   - CLAUDE.md, AGENTS* (always-loaded harness)
#   - PLAN_V2.md, PLAN.md, SYSTEM.md, EVAL_SPEC.md, WORKFLOW.md,
#     RESEARCH_AHE_ANALYSIS.md, agentic_build_workflow.md (owned planning docs)
DIFF=$(git diff upstream/main --name-only 2>/dev/null \
    | grep -v "^cosmos_lab/" \
    | grep -v "^agent/optimization/" \
    | grep -v "^configs/optimization" \
    | grep -v "^tests/optimization" \
    | grep -v "^docs/" \
    | grep -v "^bin/" \
    | grep -v "^pyproject.toml" \
    | grep -v "^uv\.lock" \
    | grep -v "^CLAUDE.md" \
    | grep -v "^AGENTS" \
    | grep -v "^PLAN_V2.md$" \
    | grep -v "^PLAN.md$" \
    | grep -v "^SYSTEM.md$" \
    | grep -v "^EVAL_SPEC.md$" \
    | grep -v "^WORKFLOW.md$" \
    | grep -v "^RESEARCH_AHE_ANALYSIS.md$" \
    | grep -v "^AGENTIC_EVAL_SPEC.md$" \
    | grep -v "^agentic_build_workflow" || true)
if [[ -z "$DIFF" ]]; then
    echo "  ✅ git diff upstream/main --name-only shows owned paths only"
    PASS=$((PASS+1))
else
    echo "  ❌ Unexpected upstream diff:"
    echo "$DIFF" | sed 's/^/    /'
    FAIL=$((FAIL+1))
fi

echo
echo "===== P0.5 D1 verifier: $PASS pass, $FAIL fail ====="
[[ $FAIL -eq 0 ]] && exit 0 || exit 1
